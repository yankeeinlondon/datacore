import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";

import inlineWorkerPlugin from "esbuild-plugin-inline-worker";

// Build the primary javascript file.
async function buildPlugin(prod) {
    fs.mkdirSync("build/plugin", { recursive: true });

    const result = await esbuild
        .build({
            banner: {
                js: `/* Datacore: Autogenerated ESBuild file. See https://github.com/blacksmithgu/datacore for source. */`,
            },
            entryPoints: ["src/main.ts"],
            bundle: true,
            metafile: true,
            plugins: [inlineWorkerPlugin({ workerName: "Datacore Indexer" })],
            external: [
                "obsidian",
                "electron",
                "@codemirror/autocomplete",
                "@codemirror/collab",
                "@codemirror/commands",
                "@codemirror/language",
                "@codemirror/lint",
                "@codemirror/search",
                "@codemirror/state",
                "@codemirror/view",
                "@lezer/common",
                "@lezer/highlight",
                "@lezer/lr",
                "pdfjs-dist",
                ...builtins,
            ],
            // Bundle workspace packages from their TypeScript sources.
            conditions: ["source"],
            format: "cjs",
            target: "es2018",
            logLevel: "info",
            sourcemap: prod ? false : "inline",
            treeShaking: true,
            outfile: "build/plugin/main.js",
        })
        .catch(() => process.exit(1));

    // Copy the manifest and styles.
    fs.copyFileSync("manifest-beta.json", "build/plugin/manifest.json");
    // The engine has no styles of its own since the views moved out; drop any stale stylesheet.
    if (fs.existsSync("build/plugin/main.css")) fs.renameSync("build/plugin/main.css", "build/plugin/styles.css");
    else fs.rmSync("build/plugin/styles.css", { force: true });
    fs.appendFileSync("build/plugin/main.js", "\n/* nosourcemap */");
    fs.writeFileSync("build/meta.json", JSON.stringify(result.metafile));
}

const prod = process.argv[2] === "production";

await buildPlugin(prod);
