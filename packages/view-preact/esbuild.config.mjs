import esbuild from "esbuild";
import fs from "node:fs";
import { builtinModules } from "node:module";
import process from "node:process";

const production = process.argv[2] === "production";
const outdir = "build/plugin";

fs.mkdirSync(outdir, { recursive: true });

const options = {
    banner: {
        js: "/* Datacore View: Preact. Autogenerated by esbuild. Source: https://github.com/yankeeinlondon/datacore */",
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/*",
        "@lezer/*",
        ...builtinModules,
        ...builtinModules.map((name) => `node:${name}`),
    ],
    // Bundle workspace packages (client, shared) from their TypeScript sources.
    conditions: ["source"],
    alias: {
        react: "preact/compat",
        "react-dom": "preact/compat",
    },
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: production ? false : "inline",
    treeShaking: true,
    outfile: `${outdir}/main.js`,
    plugins: [
        {
            // esbuild writes imported CSS next to the bundle as main.css; Obsidian loads styles.css.
            name: "obsidian-styles",
            setup(build) {
                build.onEnd(() => {
                    if (fs.existsSync(`${outdir}/main.css`)) {
                        fs.renameSync(`${outdir}/main.css`, `${outdir}/styles.css`);
                    }
                });
            },
        },
    ],
};

// manifest-beta.json tracks every version (stable and prerelease) while manifest.json tracks stable ones only, so the
// built manifest always carries the package version.
fs.copyFileSync("manifest-beta.json", `${outdir}/manifest.json`);

if (production) {
    const result = await esbuild.build({ ...options, metafile: true });
    fs.writeFileSync("build/meta.json", JSON.stringify(result.metafile));
} else {
    const context = await esbuild.context(options);
    await context.watch();
}
