import esbuild from "esbuild";
import fs from "node:fs";
import { builtinModules } from "node:module";
import process from "node:process";

const production = process.argv[2] === "production";
const outdir = "build/plugin";

fs.mkdirSync(outdir, { recursive: true });

const context = {
    banner: { js: "/* Datacore View: Preact. Autogenerated by esbuild. Source: https://github.com/yankeeinlondon/datacore */" },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/*",
        "@lezer/*",
        ...builtinModules,
        ...builtinModules.map((name) => `node:${name}`),
    ],
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: production ? false : "inline",
    treeShaking: true,
    outfile: `${outdir}/main.js`,
};

if (production) {
    await esbuild.build(context);
} else {
    await esbuild.build({ ...context, watch: true });
}

fs.copyFileSync("manifest.json", `${outdir}/manifest.json`);
